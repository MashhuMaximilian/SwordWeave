import { LibraryRefresh } from "@/components/library-refresh";
import type { Metadata, Viewport } from "next";
import localFont from "next/font/local";
import { Magra, Teko } from "next/font/google";
import Script from "next/script";
import { ClerkProvider } from "@clerk/nextjs";
import { CookieConsentManager } from "@/components/privacy/cookie-consent";
import { AppShell } from "@/components/layout/app-shell";
import { MobileViewport } from "@/components/layout/mobile-viewport";
import { RootHtml } from "@/components/layout/root-html";
import "./globals.css";

// Retain the previous typefaces behind the data-ui switch so setting
// NEXT_PUBLIC_SW_UI_VERSION=legacy is a complete visual rollback.
const legacyDisplay = Teko({
  subsets: ["latin"],
  variable: "--font-sword-display-legacy",
  weight: ["400", "700"],
  preload: false,
});

const legacyBody = Magra({
  subsets: ["latin"],
  variable: "--font-sword-body-legacy",
  weight: ["400", "700"],
  preload: false,
});

// The public hero uses Syne and Aubrey. Other faces load when their text is
// used, rather than competing with those two first-viewport fonts.
const unicaOne = localFont({
  src: "./fonts/unica-one-400-latin-f1708315.woff2",
  variable: "--font-v12-title",
  weight: "400",
  display: "swap",
  preload: false,
});

const oxanium = localFont({
  src: "./fonts/oxanium-500-latin-320e2c0e.woff2",
  variable: "--font-v12-subtitle",
  weight: "500",
  display: "swap",
  preload: false,
});

const aubrey = localFont({
  src: "./fonts/aubrey-400-latin-e006e0e2.woff2",
  variable: "--font-v12-body",
  weight: "400",
  display: "swap",
});

const syne = localFont({
  src: "./fonts/syne-600-latin-48dc6652.woff2",
  variable: "--font-v12-system",
  weight: "400 800",
  display: "swap",
});

const ibmPlexMono = localFont({
  src: [
    { path: "./fonts/ibm-plex-mono-400-latin-bc87d8e0.woff2", weight: "400" },
    { path: "./fonts/ibm-plex-mono-500-latin-a80b2cab.woff2", weight: "500" },
    { path: "./fonts/ibm-plex-mono-600-latin-2137a53a.woff2", weight: "600" },
  ],
  variable: "--font-v12-technical",
  display: "swap",
  // Technical tables can request their face when used; it does not compete
  // with the public hero's display/body fonts on every first visit.
  preload: false,
});

// Next.js 16: themeColor moved out of metadata. Putting it in metadata
// triggers "Unsupported metadata themeColor is configured in metadata
// export" on every route. Viewport exports go to a <meta name="viewport">
// tag instead, which is where the browser actually reads theme-color from.
export const metadata: Metadata = {
  metadataBase: new URL("https://www.swordweave.quest"),
  robots: { index: false, follow: true },
  title: "SwordWeave",
  description: "Open-source web engine for the SwordWeave TTRPG system.",
  manifest: "/manifest.json",
  appleWebApp: {
    capable: true,
    statusBarStyle: "black-translucent",
    title: "SwordWeave",
  },
};

export const viewport: Viewport = { themeColor: "#0b0a0f", width: "device-width", initialScale: 1, viewportFit: "cover", interactiveWidget: "resizes-content" };

export default function RootLayout({
  children,
}: Readonly<{
  children: React.ReactNode;
}>) {
  return (
    <RootHtml>
      <head>
        <link rel="describedby" href="/llms.txt" type="text/plain" />
        {/* Logo assets shipped 2026-07-14 in public/: logo-light.png
            (teal-on-transparent, light-mode brand mark), logo-dark.png
            (white-on-transparent, dark-mode brand mark). favicon-source
            is the white-bg + teal-mark source for browser/PWA icons.

            Theme-preferred favicon: we ship BOTH the white-bg AND
            dark-bg variants. Browsers with dark-mode tab chrome
            (iOS Safari dark, Chrome dark, Firefox dark) pick the
            `media="(prefers-color-scheme: dark)"` link, light-mode
            browsers pick the no-media version. Both reduce the
            visual conflict between a white-favicon-bg and a dark
            browser-chrome.

            Both favicons are 16/32/48 multi-frame .ico files
            generated by Pillow from the dark-bg source. Light-bg
            logo is also referenced as the brand mark on the homepage
            hero and the FAB speed-dial "Home" entry. */}
        <link rel="icon" href="/favicon.ico" sizes="any" />
        <link
          rel="icon"
          href="/favicon-dark.ico"
          sizes="any"
          media="(prefers-color-scheme: dark)"
        />
        <link
          rel="apple-touch-icon"
          href="/apple-touch-icon.png"
          sizes="180x180"
        />
        {/* Clerk emits its own versioned async script. Warm the matching CORS
            connection without preloading a second major-version alias. Clerk
            keeps its default UI loading for sign-in and Manage account. */}
        <link rel="dns-prefetch" href="https://clerk.swordweave.quest" />
        <link rel="preconnect" href="https://clerk.swordweave.quest" crossOrigin="anonymous" />
        <link rel="dns-prefetch" href="https://cdn.jsdelivr.net" />
      </head>
      <body
        data-ui={process.env["NEXT_PUBLIC_SW_UI_VERSION"] ?? "v12"}
        className={`${legacyDisplay.variable} ${legacyBody.variable} ${unicaOne.variable} ${oxanium.variable} ${aubrey.variable} ${syne.variable} ${ibmPlexMono.variable}`}
      >
        <Script id="swordweave-theme" strategy="beforeInteractive">
          {`
try {
  const storedTheme = window.localStorage.getItem("swordweave-theme");
  const legacyTheme = window.localStorage.getItem("sw-dark-mode");
  const useLight = storedTheme === "light" || (!storedTheme && legacyTheme === "0");
  document.documentElement.classList.toggle("dark", !useLight);
} catch {}
          `}
        </Script>
        <ClerkProvider
          signInUrl="/sign-in"
          signUpUrl="/sign-up"
          signInFallbackRedirectUrl="/atelier"
          signUpFallbackRedirectUrl="/atelier"
        >
          <MobileViewport />
          <AppShell><LibraryRefresh />{children}</AppShell>
          <CookieConsentManager />
        </ClerkProvider>
      </body>
    </RootHtml>
  );
}
