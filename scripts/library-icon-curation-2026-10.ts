export function suggestPrimitiveIcon(name: string, category: string, icons: ReadonlyArray<{ key: string; slug: string; tags: string[] }>): { key: string; source: string } {
  if (permissionIcons[name]) return { key: permissionIcons[name], source: "curated-permission" };
  if (otherPrimitiveIcons[name]) return { key: otherPrimitiveIcons[name], source: "curated-primitive" };
  if (/^(?:Tiny|Small|Medium|Large|Huge|Gargantuan) Size$/.test(name)) return { key: "delapouite/expand", source: "size-family" };
  const practice = Object.entries(practiceIcons).find(([word]) => new RegExp(`\\b${word}\\b`, "i").test(name));
  if (practice && /check|proficiency|expertise/i.test(name)) return { key: practice[1], source: "practice-family" };
  if (/attribute|physical|mental|magical/i.test(name) && /increment|attribute/i.test(name)) {
    return { key: /mental/i.test(name) ? "lorc/brain" : /magical/i.test(name) ? "lorc/magic-swirl" : "lorc/muscle-up", source: "attribute-family" };
  }
  if (/saving throw|save dc|focused presence|defense/i.test(name)) {
    return { key: /mental/i.test(name) ? "lorc/brain" : /magical/i.test(name) ? "lorc/magic-swirl" : "sbed/shield", source: "defense-family" };
  }
  if (/carry capacity|item load|equipment slot|equip slot/i.test(name)) return { key: "delapouite/backpack", source: "equipment-family" };
  if (/speed|stride|locomotion/i.test(name)) {
    return { key: /flying|flight|glid/i.test(name) ? "delapouite/fairy-wings" : /swim|aquatic/i.test(name) ? "lorc/wave-crest" : /burrow/i.test(name) ? "caro-asercion/mole" : "lorc/sprint", source: "movement-family" };
  }
  if (/dice|die block|die type|output die/i.test(name)) return { key: "delapouite/dice-six-faces-one", source: "die-family" };
  if (/\bdomain (?:of|access)\b/i.test(name)) {
    const domainName = name.replace(/^.*?domain of\s*/i, "");
    if (domainIcons[domainName]) return { key: domainIcons[domainName], source: "curated-domain" };
    const after = name.replace(/^.*?domain (?:of|access)\s*/i, "").replace(/\b(?:local|global|bounded|simple|absolute|systems|states|fields|layers|tier|i|ii|iii|iv)\b/gi, "").trim();
    const found = bestNameMatch(after, icons);
    return found ? { key: found.key, source: "domain-name" } : { key: categoryIcons.DOMAIN, source: "domain-family" };
  }
  const matched = bestNameMatch(name, icons);
  if (matched) return { key: matched.key, source: "name-match" };
  return { key: categoryIcons[category] ?? "lorc/magic-swirl", source: "category-family" };
}

const stop = new Set(["of", "the", "and", "for", "with", "tier", "type", "block", "access", "increment", "augment", "bonus", "check", "primitive", "proficiency", "upgrade", "core", "i", "ii", "iii", "iv", "pb"]);
function bestNameMatch(name: string, icons: ReadonlyArray<{ key: string; slug: string; tags: string[] }>): { key: string; score: number } | null {
  const phrase = name.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
  const words = phrase.split("-").filter(word => word.length > 2 && !stop.has(word));
  if (!words.length) return null;
  let best: { key: string; score: number } | null = null;
  for (const icon of icons) {
    const tokens = icon.slug.split("-");
    let score = icon.slug === phrase ? 20 : icon.slug.includes(phrase) && phrase.length > 5 ? 11 : 0;
    for (const word of words) {
      if (tokens.includes(word)) score += 5;
      else if (word.length > 4 && icon.slug.includes(word)) score += 2;
      else if (icon.tags.includes(word)) score += 1;
    }
    score -= icon.slug.length * 0.015;
    if (!best || score > best.score) best = { key: icon.key, score };
  }
  return best && best.score >= 4 ? best : null;
}
